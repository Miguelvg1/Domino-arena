import { strict as assert } from 'node:assert';
import { classifyLiza, lizaTotals } from './liza-calculator.mjs';
const players=['A','B','C','D'].map((member_id,i)=>({game_id:'sim-1',member_id,team:i<2?'L':'C'}));
const game={id:'sim-1',status:'en_curso',winner:null,finished_at:null,largos_score:200,cortos_score:120};
const events=[];
const add=(team,event_type,concept,points)=>events.push({game_id:game.id,team,event_type,concept,points,voided:false});
const finish=()=>{game.status='finalizada';game.winner='L';game.finished_at='2026-11-03T17:00:00Z'};
const range=['2026-11-03T04:00:00Z','2026-11-04T04:00:00Z'];
const totals=()=>lizaTotals([game],players,events,...range);
add('C','multa','multa',30);
add('C','paso_corrido','paso_corrido',30);
add('C','dos_carotas','salida_a_dos_caritas',60);
add('L','normal','dominada',200);
assert.equal(classifyLiza(game,events),'not_applicable','open game is not a liza');
finish();
assert.equal(classifyLiza(game,events),'yes','200-120 without losing dominada is a liza');
assert.equal(totals().get('A').propinadas,1);
assert.equal(totals().get('D').recibidas,1);
const correction=events.find(x=>x.team==='C'&&x.event_type==='multa');
correction.event_type='normal';correction.concept='dominada';
assert.equal(classifyLiza(game,events),'no','corrected losing dominada cancels liza');
assert.equal(totals().size,0);
correction.voided=true;game.cortos_score=90;
assert.equal(classifyLiza(game,events),'yes','voided losing dominada restores liza');
correction.voided=false;game.cortos_score=120;correction.concept=null;
assert.equal(classifyLiza(game,events),'indeterminate','unclassified correction cannot certify liza');
assert.equal(totals().get('B').indeterminadas,1);
console.log('Simulated complete match and corrections passed');
